/** Segments horizontaux pleins d'un glyphe : [colonne début, longueur, ligne depuis le BAS (0 = ligne de base)]. */
export function glyphRuns(ch: string): [number, number, number][] {
  const g = G[ch] ?? G[ch.toUpperCase()] ?? G[' ']!;
  const out: [number, number, number][] = [];
  const rows = g.length;
  for (let r = 0; r < rows; ++r) {
    const line = g[r]!;
    const fromBottom = rows - 1 - r - (rows > 7 ? 0 : 0);
    let c = 0;
    while (c < 5) {
      if (line[c] === '#') {
        let e = c;
        while (e < 5 && line[e] === '#') e++;
        out.push([c, e - c, fromBottom]);
        c = e;
      } else c++;
    }
  }
  return out;
}

/** Glyphe connu ? */
export function hasGlyph(ch: string): boolean { return ch in G; }
